package com.napier.sem;

/**
 * Represents a country
 */
public class Country {
    /**
     * Country's code
     */
    public String code;

    /**
     * Country's name
     */
    public String name;

    /**
     * Country's continent
     */
    public String continent;

    /**
     * Country's region
     */
    public String region;

    /**
     * Country's population
     */
    public int population;

    /**
     * Country's capital
     */
    public String capital;
}
